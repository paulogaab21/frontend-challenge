import { mkdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import sharp from 'sharp'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = path.join(root, 'public/images/nfts')
const widths = [96, 160, 256, 320, 480, 640, 900, 1254]
const originals = [
  ['emerald-ape', 'macaco de pelagem castanha com óculos redondos e jaqueta universitária verde'],
  ['violet-nomad', 'gorila cinza de chapéu bucket verde e moletom roxo'],
  ['ivory-baron', 'chimpanzé preto de blazer marfim e gola alta verde'],
  ['golden-beat', 'orangotango dourado de fones verdes e jaqueta creme'],
]

await mkdir(output, { recursive: true })
await mkdir(path.join(root, 'src/assets'), { recursive: true })
const manifest = {}
const sizes = []

// Sequential encoding bounds memory use and keeps output/log ordering stable.
for (const [id, alt] of originals) {
  const source = path.join(root, 'scripts/artwork-sources', `${id}.png`)
  const metadata = await sharp(source).metadata()
  if (metadata.width !== 1254 || metadata.height !== 1254) {
    throw new Error(`${id}: expected a 1254 × 1254 original`)
  }
  const { dominant } = await sharp(source).stats()
  const color = `#${[dominant.r, dominant.g, dominant.b]
    .map((channel) => channel.toString(16).padStart(2, '0'))
    .join('')}`
  const placeholder = await sharp(source)
    .resize(20, 20)
    .blur(1)
    .webp({ quality: 35, effort: 6 })
    .toBuffer()
  const sources = { avif: [], webp: [] }

  for (const format of ['avif', 'webp']) {
    for (const width of widths) {
      const filename = `${id}-${width}.${format}`
      const pipeline = sharp(source).resize(width, width, { fit: 'cover' })
      if (format === 'avif') pipeline.avif({ quality: 60, effort: 6, chromaSubsampling: '4:4:4' })
      else pipeline.webp({ quality: 85, effort: 6 })
      await pipeline.toFile(path.join(output, filename))
      sources[format].push({ width, src: `/images/nfts/${filename}` })
      sizes.push({
        artwork: id,
        format,
        width,
        bytes: (await stat(path.join(output, filename))).size,
      })
    }
  }

  const fallback = `/images/nfts/${id}-640.jpg`
  await sharp(source)
    .resize(640, 640)
    .jpeg({ quality: 88, mozjpeg: true, chromaSubsampling: '4:4:4' })
    .toFile(path.join(root, 'public', fallback.slice(1)))
  sizes.push({
    artwork: id,
    format: 'jpeg',
    width: 640,
    bytes: (await stat(path.join(root, 'public', fallback.slice(1)))).size,
  })
  manifest[id] = {
    id,
    alt,
    width: metadata.width,
    height: metadata.height,
    color,
    placeholder: `data:image/webp;base64,${placeholder.toString('base64')}`,
    sources,
    fallback,
  }
}

const generated = `// Generated by npm run assets:images. Do not edit by hand.
// Stable source order; no timestamps. Encoding settings live in scripts/optimize-images.mjs.

export type ArtworkId = ${originals.map(([id]) => JSON.stringify(id)).join(' | ')}

export type ArtworkFormat = 'avif' | 'webp'

export interface ArtworkSource {
  width: number
  src: string
}

export interface ArtworkAsset {
  id: ArtworkId
  alt: string
  width: number
  height: number
  color: string
  placeholder: string
  sources: Record<ArtworkFormat, ArtworkSource[]>
  fallback: string
}

export const artworks: Record<ArtworkId, ArtworkAsset> = ${JSON.stringify(manifest, null, 2)}
`
await writeFile(path.join(root, 'src/assets/artworks.ts'), generated, 'utf8')
console.table(sizes)
console.log(
  `Generated ${sizes.length} images (${sizes.reduce((sum, row) => sum + row.bytes, 0).toLocaleString('en-US')} bytes total).`,
)
